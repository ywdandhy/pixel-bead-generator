  url="https://image.baidu.com/search/acjson?tn=resultjson&queryWord=$encoded&word=$encoded&pn=0&rn=$rn&ie=utf-8"

  urls=$(curl -sL --max-time 10 \
    -A "$UA" \
    -H 'Accept: application/json, text/plain, */*' \
    -H 'Accept-Language: zh-CN,zh;q=0.9' \
    -H 'Referer: https://image.baidu.com/' \
    "$url" | python3 -c "
import sys, re, json
raw = sys.stdin.read()
fixed = re.sub(r',(\s*[}\]])', r'\1', raw)
try:
    d = json.loads(fixed)
except Exception:
    sys.exit()
for item in d.get('data', []):
    if not item: continue
    u = item.get('thumbURL', '')
    if not u or not u.startswith('https://img'): continue
    w = item.get('width', 0) or 0
    h = item.get('height', 0) or 0
    if w < 400 or h < 400: continue
    ratio = w / h if h else 0
    if ratio < 0.5 or ratio > 2.0: continue
    print(u)
")
  IFS=$'\n' read -d '' -ra urlArr <<< "$urls" || true

  tagsStr="['$name'"
  if [ -n "$extraTags" ]; then
    IFS=',' read -ra tagArr <<< "$extraTags"
    for t in "${tagArr[@]}"; do
      tagsStr="$tagsStr, '$t'"
    done
  fi
  tagsStr="$tagsStr]"

  if [ "$count" -eq 1 ]; then
    if [ -n "$urlArr" ]; then
      echo "  { name: '$name', category: '$cat', imageUrl: '${urlArr[0]}', tags: $tagsStr },"
    else
      echo "  // $name ($cat): 搜索失败或无合适结果"
    fi
  else
    if [ ${#urlArr[@]} -eq 0 ]; then
      echo "  // $name ($cat): 搜索失败或无合适结果"
    else
      idx=0
      for u in "${urlArr[@]}"; do
        idx=$((idx + 1))
        if [ $idx -gt $count ]; then break; fi
        echo "  { name: '$name-$idx', category: '$cat', imageUrl: '$u', tags: $tagsStr },"
      done
    fi
  fi
  sleep 0.4
done

